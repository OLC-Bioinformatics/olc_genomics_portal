#!/usr/bin/env bash
set -euo pipefail

project_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$project_root"

mode="${1:-}"
if [[ "$#" -gt 1 || ( -n "$mode" && "$mode" != "--check" ) ]]; then
    echo "Usage: $0 [--check]" >&2
    exit 2
fi

compile_options=(
    --generate-hashes
    --allow-unsafe
    --resolver=backtracking
    --no-emit-index-url
    --no-emit-trusted-host
)

compile_requirements() {
    local output_file="$1"
    local input_file="$2"
    if [[ "$mode" == "--check" ]]; then
        local compiler_output
        local preview_file
        compiler_output="$(mktemp)"
        preview_file="$(mktemp)"
        if ! pip-compile "${compile_options[@]}" --dry-run \
            --output-file "$output_file" "$input_file" > /dev/null 2> "$compiler_output"; then
            cat "$compiler_output" >&2
            rm -- "$compiler_output" "$preview_file"
            return 1
        fi
        awk '
            /^# This file is autogenerated by pip-compile/ {
                printing = 1
                print "#"
            }
            printing && /^Dry-run, so nothing updated\.$/ { exit }
            printing { print }
        ' "$compiler_output" > "$preview_file"
        if ! cmp -s "$output_file" "$preview_file"; then
            diff -u "$output_file" "$preview_file" || true
            rm -- "$compiler_output" "$preview_file"
            echo "Lock file is out of date: $output_file" >&2
            return 1
        fi
        rm -- "$compiler_output" "$preview_file"
    else
        pip-compile "${compile_options[@]}" \
            --output-file "$output_file" \
            "$input_file"
    fi
}

python_version="$(python -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
case "$python_version" in
    3.14)
        compile_requirements requirements/base.txt requirements/base.in
        compile_requirements requirements/test.txt requirements/test.in
        compile_requirements requirements/local.txt requirements/local.in
        compile_requirements storage/requirements.txt storage/requirements.in
        ;;
    3.12)
        compile_requirements batch/requirements.txt batch/requirements.in
        compile_requirements rag/requirements.txt rag/requirements.in
        ;;
    *)
        echo "Run with Python 3.14 for portal/storage locks or Python 3.12 for Batch/RAG locks." >&2
        exit 1
        ;;
esac
